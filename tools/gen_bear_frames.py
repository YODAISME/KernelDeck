#!/usr/bin/env python3
"""
gen_bear_frames.py
Asset pipeline script for KernelDeck ESP32 firmware.
Generates 3 frames of Ice Bear breathing animation from assets/challenge_bear.png
and exports them as RGB565 PROGMEM arrays into firmware/include/bear_frames.h.
"""

import os
from PIL import Image
import numpy as np

# Display Resolution
SCREEN_WIDTH = 240
SCREEN_HEIGHT = 320

# Bear Bounding Box Coordinates (Screen Space)
BEAR_X = 64
BEAR_Y = 120
BEAR_W = 112
BEAR_H = 100

# Local Waistline row (relative to BEAR_Y)
# Rows 0..WAIST_Y_LOCAL-1 shift up during breathing (head, chest, axe arm)
# Rows WAIST_Y_LOCAL..BEAR_H-1 stay grounded (hips, legs, feet)
WAIST_Y_LOCAL = 64

# Axe Glint Coordinates (Screen Space on neutral frame 0)
AXE_GLINT_X = 87
AXE_GLINT_Y = 156


def to_rgb565(r, g, b):
    """Convert 8-bit RGB to 16-bit RGB565 in host order (Adafruit_GFX format)."""
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(script_dir)
    input_path = os.path.join(project_root, "assets", "challenge_bear.png")
    output_header = os.path.join(project_root, "firmware", "include", "bear_frames.h")

    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Input image not found: {input_path}")

    # 1. Load image and ensure 240x320 nearest-neighbor scaling
    im = Image.open(input_path).convert("RGB")
    if im.size != (SCREEN_WIDTH, SCREEN_HEIGHT):
        print(f"Resizing {im.size} to ({SCREEN_WIDTH}, {SCREEN_HEIGHT}) with nearest-neighbor...")
        im = im.resize((SCREEN_WIDTH, SCREEN_HEIGHT), Image.NEAREST)

    # 2. Extract Bear Rect
    crop0 = im.crop((BEAR_X, BEAR_Y, BEAR_X + BEAR_W, BEAR_Y + BEAR_H))
    arr0 = np.array(crop0)

    # 3. Create Bear Upper Body Mask
    # Detect bear and axe pixels in rows 0..WAIST_Y_LOCAL-1
    bear_upper = np.zeros((WAIST_Y_LOCAL, BEAR_W), dtype=bool)
    for y in range(WAIST_Y_LOCAL):
        for x in range(BEAR_W):
            r, g, b = arr0[y, x][:3]
            is_sky = (r > 60 and r > g + 15 and r > b + 10) or (r > 35 and g < 25 and b < 40)
            is_mountain = (r < 45 and g < 45 and b < 65 and b >= r)
            if not (is_sky or is_mountain):
                bear_upper[y, x] = True

    # 4. Generate Frame 1: Upper body shifted up by 1 px
    arr1 = arr0.copy()
    for y in range(WAIST_Y_LOCAL - 1):
        for x in range(BEAR_W):
            if bear_upper[y + 1, x]:
                arr1[y, x] = arr0[y + 1, x]
            elif bear_upper[y, x] and not bear_upper[y + 1, x]:
                arr1[y, x] = arr0[y, x]
    for x in range(BEAR_W):
        if bear_upper[WAIST_Y_LOCAL - 1, x]:
            arr1[WAIST_Y_LOCAL - 1, x] = arr0[WAIST_Y_LOCAL, x]

    # 5. Generate Frame 2: Upper body shifted up by 2 px
    arr2 = arr0.copy()
    for y in range(WAIST_Y_LOCAL - 2):
        for x in range(BEAR_W):
            if bear_upper[y + 2, x]:
                arr2[y, x] = arr0[y + 2, x]
            elif bear_upper[y, x] and not bear_upper[y + 2, x]:
                arr2[y, x] = arr0[y, x]
    for y in [WAIST_Y_LOCAL - 2, WAIST_Y_LOCAL - 1]:
        for x in range(BEAR_W):
            if bear_upper[y, x]:
                arr2[y, x] = arr0[WAIST_Y_LOCAL, x]

    frames = [arr0, arr1, arr2]

    # Save animated GIF preview
    gif_frames = [
        Image.fromarray(arr0),
        Image.fromarray(arr1),
        Image.fromarray(arr2),
        Image.fromarray(arr1),
    ]
    gif_path = os.path.join(project_root, "assets", "bear_breathing.gif")
    gif_frames[0].save(
        gif_path, save_all=True, append_images=gif_frames[1:], duration=450, loop=0
    )
    print(f"Saved animation preview to {gif_path}")

    # 6. Convert frames to RGB565 arrays and generate bear_frames.h
    print(f"Generating C++ header: {output_header}...")
    num_pixels = BEAR_W * BEAR_H
    flash_bytes_per_frame = num_pixels * 2
    total_flash_bytes = flash_bytes_per_frame * len(frames)

    print(f"Bear Rect: {BEAR_W}x{BEAR_H} at ({BEAR_X}, {BEAR_Y})")
    print(f"Flash size per frame: {flash_bytes_per_frame} bytes ({flash_bytes_per_frame / 1024:.2f} KB)")
    print(f"Total flash for 3 frames: {total_flash_bytes} bytes ({total_flash_bytes / 1024:.2f} KB)")

    with open(output_header, "w") as f:
        f.write("#pragma once\n")
        f.write("#include <Arduino.h>\n\n")
        f.write("/**\n")
        f.write(" * KernelDeck Ice Bear Challenge Animation Assets\n")
        f.write(" * Generated by tools/gen_bear_frames.py\n")
        f.write(" * Target: ESP32 + ST7789 Adafruit_GFX (RGB565)\n")
        f.write(" */\n\n")
        f.write(f"#define BEAR_X         {BEAR_X}\n")
        f.write(f"#define BEAR_Y         {BEAR_Y}\n")
        f.write(f"#define BEAR_W         {BEAR_W}\n")
        f.write(f"#define BEAR_H         {BEAR_H}\n")
        f.write(f"#define BEAR_FRAME_COUNT 3\n")
        f.write(f"#define BEAR_FRAME_PIXELS ({BEAR_W} * {BEAR_H})\n\n")
        f.write(f"#define AXE_GLINT_X    {AXE_GLINT_X}\n")
        f.write(f"#define AXE_GLINT_Y    {AXE_GLINT_Y}\n\n")

        for idx, arr in enumerate(frames):
            f.write(f"// Frame {idx}: {'neutral' if idx == 0 else f'upper body shifted +{idx}px'}\n")
            f.write(f"const uint16_t bear_frame_{idx}[BEAR_FRAME_PIXELS] PROGMEM = {{\n")
            
            pixels = []
            for y in range(BEAR_H):
                for x in range(BEAR_W):
                    r, g, b = arr[y, x][:3]
                    pixels.append(f"0x{to_rgb565(r, g, b):04X}")

            # Write 16 values per line
            for i in range(0, len(pixels), 16):
                line = "    " + ", ".join(pixels[i:i + 16])
                if i + 16 < len(pixels):
                    line += ","
                f.write(line + "\n")
            f.write("};\n\n")

        f.write("// Pointers to the 3 animation frames\n")
        f.write("const uint16_t* const bear_frames[BEAR_FRAME_COUNT] = {\n")
        f.write("    bear_frame_0,\n")
        f.write("    bear_frame_1,\n")
        f.write("    bear_frame_2\n")
        f.write("};\n")

    print(f"Successfully generated {output_header}!")


if __name__ == "__main__":
    main()
